// Writes compiler/adapters/kit-pins.mjs: the SHA-256 of each file of the
// installed @sveltejs/kit that the compiler loads to build route manifests
// (create_manifest_data and the config defaults), and their relative imports.
// Run after checking a new Kit version: node compiler/adapters/kit-pins-update.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { kitManifestFiles } from './kit.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkg = require.resolve('@sveltejs/kit/package.json');
const dir = path.dirname(pkg);
const version = JSON.parse(readFileSync(pkg, 'utf8')).version;
const lines = kitManifestFiles(dir).map(
  f =>
    `  ${JSON.stringify(f)}: ${JSON.stringify(
      createHash('sha256')
        .update(readFileSync(path.join(dir, f)))
        .digest('hex'),
    )},`,
);
writeFileSync(
  path.join(here, 'kit-pins.mjs'),
  `// Generated by kit-pins-update.mjs for @sveltejs/kit@${version}: the files the
// compiler loads to build route manifests, by SHA-256 (a patched copy is rejected).
export const KIT_PINS = {
${lines.join('\n')}
};
`,
);
