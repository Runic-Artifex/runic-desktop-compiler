// Writes compiler/generate-pins.mjs: the SHA-256 of each generator tool's
// published files, from this repository's node_modules (installed from the
// lockfile). Run explicitly when a tool version is added; builds and
// generation only compare against the pins.
//
//   node compiler/generate-pins-update.mjs name@version …
import path from 'node:path';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { packageHash } from './generate.mjs';
import { TOOL_PINS } from './generate-pins.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
const pins = { ...TOOL_PINS };
for (const spec of process.argv.slice(2)) {
  const i = spec.lastIndexOf('@');
  const name = spec.slice(0, i);
  const dir = path.join(repo, 'node_modules', ...name.split('/'));
  const version = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8')).version;
  if (version !== spec.slice(i + 1)) throw new Error(`${name} is installed at ${version}`);
  pins[spec] = packageHash(dir);
}
const sorted = Object.entries(pins).sort(([a], [b]) => a.localeCompare(b));
writeFileSync(
  path.join(here, 'generate-pins.mjs'),
  `// Generated by compiler/generate-pins-update.mjs: the SHA-256 of each pinned
// generator tool's package files (compiler/generate.mjs \`packageHash\`).
export const TOOL_PINS = {
${sorted.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}
};
`,
);
console.log(sorted.length, 'pins');
