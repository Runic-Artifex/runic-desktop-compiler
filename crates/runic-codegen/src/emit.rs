//! Writes a generated application crate.

use crate::{Options, generate};
use base64::Engine as _;
use runic_ir::{Diagnostic, Program, Renderer, Result};
use std::path::Path;

/// Replace `data:<mime>;base64,<payload>` URLs in CSS with `runic-asset:N`
/// references and return the decoded assets (deduplicated, in first-use order).
pub fn extract_assets(css: &str) -> Result<(String, Vec<(String, Vec<u8>)>)> {
    let mut out = String::with_capacity(css.len());
    let mut assets: Vec<(String, Vec<u8>)> = vec![];
    let mut rest = css;
    while let Some(start) = rest.find("data:") {
        out.push_str(&rest[..start]);
        let tail = &rest[start + 5..];
        let end = tail.find(['"', '\'', ')']).unwrap_or(tail.len());
        let url = &tail[..end];
        let Some((mime, payload)) = url.split_once(";base64,") else {
            return Err(Diagnostic::new(
                "E_ASSET",
                "Only base64 data URLs can be embedded",
                None,
            ));
        };
        let bytes = base64::engine::general_purpose::STANDARD
            .decode(payload.trim())
            .map_err(|e| Diagnostic::new("E_ASSET", format!("Invalid base64 asset: {e}"), None))?;
        let index = match assets.iter().position(|(m, b)| m == mime && *b == bytes) {
            Some(i) => i,
            None => {
                assets.push((mime.to_owned(), bytes));
                assets.len() - 1
            }
        };
        out.push_str(&format!("runic-asset:{index}"));
        rest = &tail[end..];
    }
    out.push_str(rest);
    Ok((out, assets))
}

fn io(e: std::io::Error) -> Diagnostic {
    Diagnostic::new("E_OUTPUT", e.to_string(), None)
}

/// The `[patch.…]` sections of a workspace manifest (crates.io and git
/// sources), verbatim (empty if there are none). A generated app is a
/// workspace of its own, so it repeats the compiler workspace's patches to
/// resolve the same crates as the Cargo.lock it copies.
pub fn patch_section(manifest: &str) -> String {
    let mut section = String::new();
    let mut inside = false;
    for line in manifest.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            inside = trimmed.starts_with("[patch.");
        }
        if inside {
            section.push_str(line);
            section.push('\n');
        }
    }
    section
}

/// Write the generated crate for `program` into `out`.
///
/// `runtime` is the path of `crates/runic-runtime`; `lock` the workspace
/// Cargo.lock whose dependency versions the app must reuse.
pub fn write_crate(
    program: &Program,
    ir_hash: &str,
    out: &Path,
    runtime: &Path,
    lock: &Path,
    options: &Options,
) -> Result<()> {
    let (css, assets) = extract_assets(&program.styles.css)?;
    let mimes: Vec<String> = assets.iter().map(|(m, _)| m.clone()).collect();
    let app = generate(program, ir_hash, &css, &mimes, options)?;
    std::fs::create_dir_all(out.join("src")).map_err(io)?;
    std::fs::create_dir_all(out.join("assets")).map_err(io)?;
    for (i, (_, bytes)) in assets.iter().enumerate() {
        std::fs::write(out.join("assets").join(i.to_string()), bytes).map_err(io)?;
    }
    std::fs::write(out.join("src/app.rs"), app).map_err(io)?;
    std::fs::write(
        out.join("src/main.rs"),
        "mod app;\nfn main() {\n    runic_runtime::launch::<app::App>();\n}\n",
    )
    .map_err(io)?;
    let renderer = match program.renderer {
        Renderer::Cpu => "renderer-cpu",
        Renderer::Gpu => "renderer-gpu",
    };
    // Only programs with inline SVG link Blitz's SVG support.
    let features = if program.uses_svg() {
        format!("\"{renderer}\", \"svg\"")
    } else {
        format!("\"{renderer}\"")
    };
    let manifest = format!(
        r#"# Generated by runic-codegen. Do not edit.
[package]
name = "runic-app"
version = "0.1.0"
edition = "2024"
publish = false

[dependencies]
runic-runtime = {{ path = {runtime:?}, default-features = false, features = [{features}] }}

[features]
probe = ["runic-runtime/probe"]

[profile.dev]
debug = 0

[profile.release]
opt-level = "s"
strip = true
debug = 0
codegen-units = 1
panic = "abort"

# A standalone workspace: generated apps live inside the compiler repository.
[workspace]

{patches}"#,
        runtime = runtime.display().to_string(),
        patches =
            patch_section(&std::fs::read_to_string(lock.with_file_name("Cargo.toml")).map_err(io)?),
    );
    std::fs::write(out.join("Cargo.toml"), manifest).map_err(io)?;
    std::fs::copy(lock, out.join("Cargo.lock")).map_err(io)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn copies_the_workspace_patches() {
        let manifest = "[workspace]\nmembers = []\n\n# Forks.\n[patch.crates-io]\n# A fork.\nvello_cpu = { git = \"file:///v\", rev = \"1\" }\n\n[profile.dev]\ndebug = 0\n";
        assert_eq!(
            patch_section(manifest),
            "[patch.crates-io]\n# A fork.\nvello_cpu = { git = \"file:///v\", rev = \"1\" }\n\n"
        );
        assert_eq!(patch_section("[workspace]\n"), "");
        // The compiler workspace's own manifest has the renderer forks.
        let root = include_str!("../../../Cargo.toml");
        assert!(patch_section(root).contains("vello_cpu = "));
        // Git sources too (the Taffy fork).
        assert!(
            patch_section(root)
                .contains("[patch.\"https://github.com/DioxusLabs/taffy\"]\ntaffy = ")
        );
    }

    #[test]
    fn extracts_and_deduplicates_data_urls() {
        let css = r#"@font-face{src:url("data:font/woff2;base64,AAEC") format("woff2")}
            @font-face{src:url(data:font/woff2;base64,AAEC)} p{color:red}"#;
        let (out, assets) = extract_assets(css).unwrap();
        assert_eq!(assets, vec![("font/woff2".to_owned(), vec![0, 1, 2])]);
        assert!(out.contains(r#"url("runic-asset:0") format("woff2")"#));
        assert!(out.contains("url(runic-asset:0)"));
        assert!(out.ends_with("p{color:red}"));
    }
}
