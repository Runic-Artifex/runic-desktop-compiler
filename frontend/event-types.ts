/**
 * Native types Chromium never dispatches where the runtime and the harness
 * run (no touch device, no drag and drop, no find-in-page, the document
 * stays visible): their listeners run for the events script dispatches.
 */
export const NEVER_FIRED_TYPES: readonly string[] = [
  'touchstart',
  'touchmove',
  'touchend',
  'touchcancel',
  'dragstart',
  'drag',
  'dragend',
  'dragenter',
  'dragleave',
  'dragover',
  'drop',
  'beforematch',
  'visibilitychange',
];

/**
 * Whether a listener of type `name` can be added at some target: a custom
 * type, a native one Chromium never fires there, or one the runtime fires
 * (not `load` and `error`, which reach only images and the page).
 */
export function listenableType(name: string): boolean {
  if (!NATIVE_TYPES.includes(name) || NEVER_FIRED_TYPES.includes(name)) return true;
  return FIRED_TYPES.includes(name) && name !== 'load' && name !== 'error';
}

/** Whether `name` is a custom event type (not one Chromium dispatches). */
export function customType(name: string): boolean {
  return name !== '' && !NATIVE_TYPES.includes(name);
}
